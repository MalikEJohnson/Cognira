import { build } from "esbuild";
import { rm } from "node:fs/promises";

/**
 * Bundles our own TypeScript into one plain JavaScript file for the
 * serverless function.
 *
 * Node ESM requires a ".js" suffix on relative imports even when the file on
 * disk is ".ts". Bundlers vary in whether they map that back, and when one
 * does not, none of src/ makes it into the deployed function and it dies on
 * import with no useful message. Resolving those imports here, ahead of
 * deployment, removes the guesswork.
 *
 * node_modules stay external — they resolve by name, which was never the
 * problem, and several ship native binaries that must not be inlined.
 */
await rm("dist/app.js", { force: true });

await build({
  entryPoints: ["src/serverless.ts"],
  outfile: "dist/app.js",
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  packages: "external",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Generated by scripts/build-function.mjs — edit src/, not this file.",
  },
});

console.log("built dist/app.js");
